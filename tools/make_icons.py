def from_ascii(rows):
    assert len(rows) == 16, len(rows)
    im = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(rows):
        row = row.ljust(16, '.')[:16]
        for x, ch in enumerate(row):
            c = PAL.get(ch)
            if c: im.putpixel((x, y), c)
    return im

def outline(im):
    """Contorno escuro de 1px ao redor de tudo que ainda não tem contorno."""
    out = im.copy()
    px = im.load()
    for y in range(16):
        for x in range(16):
            if px[x, y][3] == 0:
                for dx, dy in ((1,0),(-1,0),(0,1),(0,-1)):
                    nx, ny = x+dx, y+dy
                    if 0 <= nx < 16 and 0 <= ny < 16 and px[nx, ny][3] and px[nx, ny] != OUTLINE:
                        out.putpixel((x, y), OUTLINE); break
    return out

